import { createServer } from 'node:http';
import { createHash, createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
const hash = body => createHash('sha256').update(body).digest('hex');
const mac = (key, text) => createHmac('sha256', key).update(text).digest();
const encode = value => encodeURIComponent(value).replace(/[!'()*]/g,c=>`%${c.charCodeAt(0).toString(16).toUpperCase()}`);
const xml = text => text.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
export async function startTestServices() {
  const secret=randomBytes(32).toString('hex'); const files=new Map(); const webhooks=[];
  let putCountdown=0,webhookFailures=0,aiCalls=0,signatureFailures=0;
  const server=createServer(async(req,res)=>{
    try {
      const chunks=[];for await (const chunk of req) chunks.push(chunk);
      const bytes=Buffer.concat(chunks);const url=new URL(req.url,'http://localhost');
      const reply=(code,body,type='application/json')=>{res.writeHead(code,{'content-type':type});res.end(typeof body==='string'||Buffer.isBuffer(body)?body:JSON.stringify(body));};
      if (url.pathname==='/__test/state') return reply(200,{files:[...files.keys()],webhooks,aiCalls,signatureFailures});
      if (url.pathname==='/__test/fail-put') {putCountdown=JSON.parse(bytes).after;return reply(200,{});}
      if (url.pathname==='/__test/fail-webhook') {webhookFailures=1;return reply(200,{});}
      if (url.pathname==='/hook') {if(webhookFailures-- >0)return reply(429,{});webhooks.push(JSON.parse(bytes));return reply(204,'');}
      if (url.pathname.startsWith('/ai/')) {
        if (req.headers.authorization!=='Bearer test-ai-key')return reply(401,{});
        aiCalls++;
        if(url.pathname.endsWith('/models'))return reply(200,{data:[{id:'test-model'}]});
        const input=JSON.parse(bytes);
        if(url.pathname.endsWith('/embeddings')) {
          const texts=Array.isArray(input.input)?input.input:[input.input];
          return reply(200,{data:texts.map((text,index)=>({index,embedding:[String(text).toLowerCase().includes('needle')?1:0,1]})).reverse()});
        }
        if(url.pathname.endsWith('/chat/completions')) {
          const generate=input.messages?.[0]?.content.includes('valid JSON');
          const content=generate?JSON.stringify({title:'Feature: generated task',category:'feature',priority:'medium',notes:'Generated by test provider',project:'',checklist:['Implement','Test']}):'สวัสดีครับ รายงานงานวันนี้ ขอบคุณครับ';
          return reply(200,{choices:[{message:{content}}]});
        }
        if(url.pathname.endsWith('/audio/speech'))return reply(200,Buffer.from('ID3-test-audio'),'audio/mpeg');
      }
      if (!url.pathname.startsWith('/bucket')) return reply(404,{});
      const auth=req.headers.authorization||'';
      const match=auth.match(/^AWS4-HMAC-SHA256 Credential=test-access\/(\d{8})\/([^/]+)\/s3\/aws4_request, SignedHeaders=host;x-amz-content-sha256;x-amz-date, Signature=([\da-f]+)$/);
      let valid=false;
      if(match) {
        const [,date,region,sig]=match;const payload=hash(bytes);const query=[...url.searchParams].map(([k,v])=>[encode(k),encode(v)]).sort(([a,b],[c,d])=>a.localeCompare(c)||b.localeCompare(d)).map(([k,v])=>`${k}=${v}`).join('&');
        const canonical=`${req.method}\n${url.pathname}\n${query}\nhost:${req.headers.host}\nx-amz-content-sha256:${payload}\nx-amz-date:${req.headers['x-amz-date']}\n\nhost;x-amz-content-sha256;x-amz-date\n${payload}`;
        const scope=`${date}/${region}/s3/aws4_request`;const sign=`AWS4-HMAC-SHA256\n${req.headers['x-amz-date']}\n${scope}\n${hash(canonical)}`;
        const key=mac(mac(mac(mac(`AWS4${secret}`,date),region),'s3'),'aws4_request');const expected=mac(key,sign).toString('hex');
        valid=sig.length===expected.length&&timingSafeEqual(Buffer.from(sig),Buffer.from(expected))&&req.headers['x-amz-content-sha256']===payload;
      }
      if(!valid){signatureFailures++;return reply(403,{error:'invalid signature'});}
      const key=decodeURIComponent(url.pathname.slice('/bucket/'.length));
      if(req.method==='PUT'){
        if(putCountdown>0&&--putCountdown===0)return reply(503,{});
        files.set(key,{bytes,type:req.headers['content-type'],date:new Date().toISOString()});return reply(200,'');
      }
      if(req.method==='DELETE'){files.delete(key);return reply(204,'');}
      if(req.method==='GET'&&url.searchParams.get('list-type')==='2'){
        const start=Number(url.searchParams.get('continuation-token')||0);const entries=[...files.entries()].sort(([a],[b])=>a.localeCompare(b));
        const contents=entries.slice(start,start+2).map(([key,file])=>`<Contents><Key>${xml(key)}</Key><Size>${file.bytes.length}</Size><LastModified>${file.date}</LastModified><ETag>test-etag</ETag></Contents>`).join('');
        const next=start+2<entries.length?`<NextContinuationToken>${start+2}</NextContinuationToken>`:'';
        return reply(200,`<ListBucketResult>${contents}${next}</ListBucketResult>`,'application/xml');
      }
      if(req.method==='GET'&&files.has(key)){const file=files.get(key);return reply(200,file.bytes,file.type);}
      return reply(404,{});
    } catch {res.writeHead(500);res.end('Test service failure');}
  });
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  return {url:`http://127.0.0.1:${server.address().port}`,secret,close:()=>new Promise(resolve=>server.close(resolve))};
}
